def detect_signals(text: str) -> list[str]:
    """规则词典信号检测，返回命中的信号类型列表（按规则顺序）。"""
    hits: list[str] = []
    for key, keywords in SIGNAL_RULES:
        if key in hits:
            continue
        for kw in keywords:
            if kw in text:
                hits.append(key)
                break
    return hits


def build_signal_block(signals: list[str]) -> str:
    if not signals:
        return ""
    lines = []
    for sig in signals:
        guide = SIGNAL_GUIDANCE.get(sig)
        if guide:
            lines.append(f"- 检测到信号「{sig}」：{guide}")
    if not lines:
        return ""
    return "信号提示（必须遵守）：\n" + "\n".join(lines) + "\n\n"
